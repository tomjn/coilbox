//! Taking one field out of a unit's table (issue #3245), the way a re-export
//! of a built unit drops a field the build no longer writes.

use coilbox_unitpatch::{
    field_value, parse_path, remove, same_value, Patched, Refusal, RefusalKind, Value,
};

const EXPORTED: &str = r#"-- tank, generated by coilbox's unit builder.

return {
  ["tank"] = {
    objectname = "tank",
    usepiececollisionvolumes = true,
    customparams = { unitdefbuildtime = 100, note = "kept" },
    builder = true,
    workertime = 100,
  },
}
"#;

fn run(source: &str, unit: &str, path: &str) -> Result<Patched, Refusal> {
    let root = tempfile::tempdir().expect("temp dir");
    remove(
        source,
        unit,
        &parse_path(path).expect("valid path"),
        root.path(),
    )
}

#[test]
fn removes_a_field_and_its_line() {
    let patched = run(EXPORTED, "tank", "usepiececollisionvolumes").expect("removed");
    assert!(patched.changed);
    assert_eq!(
        patched.text,
        EXPORTED.replacen("    usepiececollisionvolumes = true,\n", "", 1)
    );
}

#[test]
fn matches_the_key_without_regard_to_case() {
    let patched = run(EXPORTED, "TANK", "WorkerTime").expect("removed");
    assert_eq!(
        patched.text,
        EXPORTED.replacen("    workertime = 100,\n", "", 1)
    );
}

#[test]
fn removes_a_field_inside_a_table() {
    let patched = run(EXPORTED, "tank", "customparams.unitdefbuildtime").expect("removed");
    assert!(patched.changed);
    assert!(patched.text.contains("customparams = { note = \"kept\" },"));
}

#[test]
fn a_field_that_is_not_there_is_no_change() {
    let patched = run(EXPORTED, "tank", "maxslope").expect("nothing to do");
    assert!(!patched.changed);
    assert_eq!(patched.text, EXPORTED);
}

#[test]
fn refuses_a_field_set_again_later_in_the_file() {
    let source = "local u = { speed = 2 }\nu.speed = 3\nreturn { tank = u }\n";
    let refusal = run(source, "tank", "speed").expect_err("refused");
    assert_eq!(refusal.kind, RefusalKind::PostCheckFailed);
}

#[test]
fn refuses_a_unit_that_is_not_there() {
    let refusal = run(EXPORTED, "other", "builder").expect_err("refused");
    assert_eq!(refusal.kind, RefusalKind::UnitNotFound);
}

#[test]
fn reads_a_field_back_for_comparison() {
    let root = tempfile::tempdir().expect("temp dir");
    let table = coilbox_unitpatch::evaluate(EXPORTED, root.path()).expect("runs");
    let path = parse_path("customparams.unitdefbuildtime").unwrap();
    let found = field_value(&table, "Tank", &path).expect("present");
    assert!(same_value(found, &Value::Number(100.0)));
    assert!(!same_value(found, &Value::Number(101.0)));
    assert!(field_value(&table, "tank", &parse_path("maxslope").unwrap()).is_none());
}
