/**
 * Blending between actions under luajit (#3358).
 *
 * The harness has no `GetPieceRotation`, as the preview's runtime has none, so
 * a script that passes here reads where a piece is from its own bookkeeping.
 */

const POSE_C = {
  id: "pose-c",
  name: "Aimed",
  pieces: { arm: { turn: [2, 0, 0] as [number, number, number] } },
};

/** Plant walks, Aim swings the arm it shares to 2 rad. */
function blended(extra = {}) {
  return unit({
    poses: [POSE_A, POSE_B, POSE_C],
    actions: [
      action({ blendOut: 1 }),
      action({
        id: "aim",
        name: "Aim",
        trigger: "Shot1",
        loop: false,
        keys: [{ pose: "pose-c", seconds: 5 }],
        blendIn: 0.5,
      }),
    ],
    ...extra,
  });
}

describe("a unit with no blend set (#3358)", () => {
  it("writes the script #3356 wrote", () => {
    expect(buildLuaScript(unit())).toMatchInlineSnapshot(`
      "-- mech, generated by coilbox's unit builder.
      -- Safe to edit: once you change this file, an export leaves it alone.

      local base = piece("base")
      local arm = piece("arm")
      local hatch = piece("hatch")

      local SIG_ACTION_PLANT = "SIG_ACTION_PLANT"

      -- Action: Plant
      local function action_Plant()
        SetSignalMask(SIG_ACTION_PLANT)
        Turn(arm, x_axis, 1, 1)
        Move(hatch, y_axis, 4, 4)
        Sleep(990)
        Turn(arm, x_axis, -0.5, 0.75)
        Turn(arm, z_axis, 0.8, 0.4)
        Move(hatch, y_axis, 0, 2)
        Sleep(1980)
        while true do
          Turn(arm, x_axis, 1, 1.5)
          Turn(arm, z_axis, 0, 0.8)
          Move(hatch, y_axis, 4, 4)
          Sleep(990)
          Turn(arm, x_axis, -0.5, 0.75)
          Turn(arm, z_axis, 0.8, 0.4)
          Move(hatch, y_axis, 0, 2)
          Sleep(1980)
        end
      end

      local function action_PlantStop()
        Signal(SIG_ACTION_PLANT)
        Turn(arm, x_axis, 0, 4)
        Turn(arm, z_axis, 0, 4)
        Move(hatch, y_axis, 0, 4)
      end

      function script.Create()
      end

      function script.StartMoving()
        Signal(SIG_ACTION_PLANT)
        StartThread(action_Plant)
      end

      function script.StopMoving()
        action_PlantStop()
      end

      function script.Activate()
      end

      function script.Deactivate()
      end

      function script.AimWeapon1(heading, pitch)
        return true
      end

      function script.AimFromWeapon1()
      end

      function script.QueryWeapon1()
      end

      function script.Shot1()
      end

      function script.StartBuilding(heading, pitch)
        SetUnitValue(COB.INBUILDSTANCE, 1)
      end

      function script.StopBuilding()
        SetUnitValue(COB.INBUILDSTANCE, 0)
      end

      function script.QueryNanoPiece()
        return base
      end

      function script.Killed(recentDamage, maxHealth)
        Explode(base, SFX.SHATTER)
        return 1
      end
      "
    `);
  });
});

describe("an action that starts over another (#3358)", () => {
  const lua = buildLuaScript(blended());
  // Plant starts on frame 0 and is 2 s in, between its two keys, when Aim fires.
  const SWITCH = 2 * FPS;
  const rows = run(
    lua,
    [
      { frame: 0, callin: "StartMoving" },
      { frame: SWITCH, callin: "Shot1" },
    ],
    6 * FPS,
    [ARM_X],
  );
  /** The arm once `frame` frames have passed. */
  const armAt = (frame: number) => rows[frame - 1][0];

  it("is part way between its keys when it is switched", () => {
    expect(armAt(SWITCH)).toBeCloseTo(0.25, 1);
  });

  it("reaches the first key in the blend time, within a frame", () => {
    const blend = 0.5 * FPS;
    // Fastest axis speed: (2 - 0.25) rad over half a second.
    const speed = 1.75 / 0.5;
    expect(Math.abs(armAt(SWITCH + blend) - 2)).toBeLessThanOrEqual(
      allowance(speed),
    );
    // And not before it: at the halfway frame it is still on its way.
    expect(armAt(SWITCH + Math.floor(blend / 2))).toBeGreaterThan(0.8);
    expect(armAt(SWITCH + Math.floor(blend / 2))).toBeLessThan(1.4);
  });

  it("leaves from where the arm was, not from rest", () => {
    // A frame after the switch the arm has moved one frame's step from 0.25.
    const step = 1.75 / 0.5 / FPS;
    expect(Math.abs(armAt(SWITCH + 1) - (armAt(SWITCH) + step))).toBeLessThan(
      allowance(1.75 / 0.5),
    );
  });

  it("holds the key, because the walk no longer drives the arm", () => {
    for (const frame of [SWITCH + 20, SWITCH + 60, 6 * FPS]) {
      expect(Math.abs(armAt(frame) - 2)).toBeLessThan(1e-6);
    }
  });

  it("does not read a piece back from the engine", () => {
    expect(lua).not.toMatch(/GetPiece(Rotation|Translation|Position)/);
    expect(lintLuaCallins(lua)).toEqual([]);
  });
});

describe("a looping action that stops", () => {
  const WATCH = [ARM_X, HATCH_Y];
  const STOP = 2 * FPS;

  it("eases back to rest over its blend out", () => {
    const rows = run(
      buildLuaScript(blended()),
      [
        { frame: 0, callin: "StartMoving" },
        { frame: STOP, callin: "StopMoving" },
      ],
      6 * FPS,
      WATCH,
    );
    const at = (frame: number) => rows[frame - 1];
    const [armNow, hatchNow] = at(STOP);
    // Linear back to zero over 1 s, so halfway the distance is half.
    const halfway = at(STOP + FPS / 2);
    expect(Math.abs(halfway[0] - armNow / 2)).toBeLessThanOrEqual(
      allowance(armNow),
    );
    expect(Math.abs(halfway[1] - hatchNow / 2)).toBeLessThanOrEqual(
      allowance(hatchNow),
    );
    // And at rest after it, to within a frame of the faster axis.
    const done = at(STOP + FPS);
    expect(Math.abs(done[0])).toBeLessThanOrEqual(allowance(armNow));
    expect(Math.abs(done[1])).toBeLessThanOrEqual(allowance(hatchNow));
    expect(at(6 * FPS - 1)).toEqual([0, 0]);
  });

  it("returns at the old fixed speed when it blends out over no time", () => {
    const project = unit({
      actions: [action({ blendIn: 0.5, blendOut: 0 })],
    });
    const lua = buildLuaScript(project);
    expect(lua).toContain("ActTurn(arm, x_axis, 0, 4)");
    const rows = run(
      lua,
      [
        { frame: 0, callin: "StartMoving" },
        { frame: STOP, callin: "StopMoving" },
      ],
      6 * FPS,
      WATCH,
    );
    // The arm is 0.25 rad out, so at 4 rad a second it is home in 2 frames.
    expect(rows[STOP + 3][0]).toBe(0);
  });

  it("does not drag a piece another action has taken back to rest", () => {
    const rows = run(
      buildLuaScript(blended()),
      [
        { frame: 0, callin: "StartMoving" },
        { frame: STOP, callin: "Shot1" },
        { frame: 4 * FPS, callin: "StopMoving" },
      ],
      8 * FPS,
      WATCH,
    );
    // The arm is Aim's and stays at 2. The hatch is only the walk's and goes home.
    expect(rows.at(-1)).toEqual([2, 0]);
  });
});

describe("a piece two actions share", () => {
  it("is named once, with both actions, in the problems list", () => {
    const messages = actionProblems(blended()).map((p) => p.message);
    expect(messages).toEqual([
      "Plant and Aim both move arm. The one started last takes it.",
    ]);
  });

  it("says who wins by calling order when nothing blends", () => {
    const messages = actionProblems(
      unit({
        poses: [POSE_A, POSE_B, POSE_C],
        actions: [
          action(),
          action({ id: "aim", name: "Aim", trigger: "Shot1" }),
        ],
      }),
    ).map((p) => p.message);
    expect(messages).toEqual([
      "Plant and Aim both move arm, hatch. The one called last wins.",
    ]);
  });

  it("is not reported for pieces that are apart", () => {
    const apart = unit({
      poses: [
        POSE_B,
        { id: "pose-c", name: "Hatch", pieces: { hatch: { move: [0, 1, 0] } } },
      ],
      actions: [
        action({ keys: [{ pose: "pose-b", seconds: 1 }], loop: false }),
        action({
          id: "aim",
          name: "Aim",
          trigger: "Shot1",
          loop: false,
          keys: [{ pose: "pose-c", seconds: 1 }],
        }),
      ],
      actionBlend: 0.4,
    });
    expect(actionProblems(apart)).toEqual([]);
  });
});

describe("a unit whose blends are 0 or unset", () => {
  it("writes it again when every blend is 0", () => {
    const plain = buildLuaScript(unit());
    expect(
      buildLuaScript(
        unit({
          actionBlend: 0,
          actions: [action({ blendIn: 0, blendOut: 0 })],
        }),
      ),
    ).toBe(plain);
    expect(unitBlends(unit())).toBe(false);
  });

  it("uses the project's time for an action that sets none of its own", () => {
    const withDefault = setDefaultBlend(unit(), 0.4);
    expect(unitBlends(withDefault)).toBe(true);
    expect(buildLuaScript(withDefault)).toContain(
      "BlendTurn(arm, x_axis, 1, 0.4)",
    );
    expect(buildLuaScript(withDefault)).toContain(
      "BlendTurn(arm, x_axis, 0, 0.4)",
    );
    const own = setActionBlend(withDefault, "act", "blendIn", 0.2);
    expect(buildLuaScript(own)).toContain("BlendTurn(arm, x_axis, 1, 0.2)");
    const back = setActionBlend(own, "act", "blendIn", null);
    expect(back.actions?.[0].blendIn).toBeUndefined();
    expect(setDefaultBlend(withDefault, 0).actionBlend).toBeUndefined();
  });
});

describe("blend times in a saved unit", () => {
  it("survive a save and a load, and drop what is not a time", () => {
    const loaded = parseLegoProjectData(
      JSON.parse(
        JSON.stringify({
          ...unit({ actionBlend: 0.3 }),
          actions: [
            { ...action(), blendIn: 0.5, blendOut: -1 },
            { ...action({ id: "b", name: "B" }), blendIn: "slow" },
          ],
        }),
      ),
    );
    expect(loaded?.actionBlend).toBe(0.3);
    expect(loaded?.actions?.[0]).toMatchObject({ blendIn: 0.5 });
    expect(loaded?.actions?.[0]).not.toHaveProperty("blendOut");
    expect(loaded?.actions?.[1]).not.toHaveProperty("blendIn");
  });
});
